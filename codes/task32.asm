.MODEL SMALL
.STACK 100H

.DATA
    MY_TEXT        DB ' I AM A PROUD PAKISTANI$', 0
    SHOW_VOWEL     DB 'VOWELS: $'
    SHOW_CONSONANT DB 13, 10, 'CONSONANTS: $'
    COUNT_VOWELS   DW 0
    COUNT_CONS     DW 0

.CODE
BEGIN:
    MOV AX, @DATA
    MOV DS, AX

    MOV SI, OFFSET MY_TEXT

CHECK_LOOP:
    MOV AL, [SI]
    CMP AL, '$'
    JE DISPLAY_RESULTS

    CMP AL, 'A'
    JL SKIP_THIS
    CMP AL, 'Z'
    JLE TO_LOWER
    CMP AL, 'a'
    JL SKIP_THIS
    CMP AL, 'z'
    JG SKIP_THIS

    JMP VOWEL_CHECK

TO_LOWER:
    ADD AL, 32

VOWEL_CHECK:
    CMP AL, 'a'
    JE FOUND_VOWEL
    CMP AL, 'e'
    JE FOUND_VOWEL
    CMP AL, 'i'
    JE FOUND_VOWEL
    CMP AL, 'o'
    JE FOUND_VOWEL
    CMP AL, 'u'
    JE FOUND_VOWEL

    INC COUNT_CONS
    JMP MOVE_NEXT

FOUND_VOWEL:
    INC COUNT_VOWELS
    JMP MOVE_NEXT

SKIP_THIS:
    JMP MOVE_NEXT

MOVE_NEXT:
    INC SI
    JMP CHECK_LOOP

DISPLAY_RESULTS:
    MOV DX, OFFSET SHOW_VOWEL
    CALL PRINT_STR

    MOV AX, COUNT_VOWELS
    CALL PRINT_NUM

    MOV DX, OFFSET SHOW_CONSONANT
    CALL PRINT_STR

    MOV AX, COUNT_CONS
    CALL PRINT_NUM

    MOV AH, 4CH
    INT 21H


PRINT_STR:
    MOV AH, 09H
    INT 21H
    RET


PRINT_NUM:
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX

    XOR CX, CX
    MOV BX, 10

NUM_TO_ASCII:
    XOR DX, DX
    DIV BX
    PUSH DX
    INC CX
    TEST AX, AX
    JNZ NUM_TO_ASCII

PRINT_DIGITS:
    POP DX
    ADD DL, '0'
    MOV AH, 02H
    INT 21H
    LOOP PRINT_DIGITS

    POP DX
    POP CX
    POP BX
    POP AX
    RET
